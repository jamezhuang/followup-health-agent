def source_priority(source):
    """Prefer verified publishers without treating guessed publisher names as proof."""
    authority = source.get('authority', '')
    if authority in {'government', 'registered', 'government_linked'}:
        return 0
    if authority == 'published_local':
        return 1
    return 2
