def answer_frame(goal, context=None, policy=None):
    import re
    context,policy=context or {},policy or {}
    topics=set(context.get('topics',[]))
    if policy.get('task')=='count': style='count'
    elif re.search(r'对比|比较|哪个好|哪家好|区别|怎么选|如何选',goal) and len(context.get('names',[]))>1:
        style='comparison'
    elif context.get('kind')=='directory' and (context.get('care_topic') or context.get('department')):
        style='disease_choice'
    elif context.get('kind')=='directory': style='directory'
    elif topics & {'specialty','departments'}: style='specialty'
    elif topics & {'address','transport'}: style='address'
    elif topics & {'appointment'}: style='appointment'
    elif topics & {'cost'}: style='cost'
    else: style='service'
    categories=context.get('service_categories') or service_categories(goal)
    return style, ANSWER_FRAMES[style]+'\n'+service_frame(categories)


